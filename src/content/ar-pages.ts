/** Arabic plural forms for a project count (1, 2, 3–10, 11+). */
function projectCount(count: number): string {
  if (count === 1) return "مشروع واحد";
  if (count === 2) return "مشروعان";
  if (count >= 3 && count <= 10) return `${count} مشروعات`;
  return `${count} مشروعًا`;
}

