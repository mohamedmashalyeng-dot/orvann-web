export const arProjects: Project[] = enProjects.map((project) => {
  const words = text[project.slug];
  // A new English project without its Arabic text fails the build instead of shipping English.
  if (!words) throw new Error(`Missing Arabic text for project "${project.slug}" in ar-projects.ts`);
  const { imageAlt, galleryAlts, ...fields } = words;
  return {
    ...project,
    ...fields,
    image: { ...project.image, alt: imageAlt },
    gallery: project.gallery?.map((image, index) => {
      const alt = galleryAlts?.[index];
      if (!alt) throw new Error(`Missing Arabic alt text for gallery image ${index + 1} of "${project.slug}"`);
      return { ...image, alt };
    }),
  };
});
